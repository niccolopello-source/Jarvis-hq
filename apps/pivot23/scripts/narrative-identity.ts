// Dev tool: rewrites src/lib/pivot/narrative/catalog-identity.ts from the English catalog.
//   node --import=tsx scripts/narrative-identity.ts
// The identity entries (key reads the same in English: names, numbers, brand words) are the only
// part of the English catalog that Spanish and Chinese need; see narrative/index.ts.
import { writeFileSync } from "node:fs";
import { NARRATIVE_EN } from "../src/lib/pivot/narrative/catalog-en.ts";
import { identityEntries } from "../src/lib/pivot/narrative/identity.ts";

const entries = identityEntries(NARRATIVE_EN);
writeFileSync(
  "src/lib/pivot/narrative/catalog-identity.ts",
  `/**\n` +
    ` * GENERATED by scripts/narrative-identity.ts from catalog-en.ts: do not edit by hand.\n` +
    ` * English catalog entries whose text is the Italian key itself (proper names, numbers, brand words).\n` +
    ` * Spanish and Chinese load this small chunk instead of the whole English catalog (2026-11-10).\n` +
    ` */\n` +
    `export const NARRATIVE_IDENTITY: Readonly<Record<string, string>> = {\n` +
    entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n") +
    `\n};\n`,
);
console.log(entries.length);
